"""Prepare the PWA's generated assets from the iOS project's sources of truth.

- books.js   from BibleCore's BookCatalog.swift (66 rows, same names and slugs)
- bsb.json   the iOS app bundle's text, with psalm titles, three Proverbs section openings and
             Habakkuk's closing note split out of their verses (the bundle's source, bsb.txt,
             runs them into the verse)
- ml/mal1910.json   Malayalam Sathyavedapusthakam 1910 (contemporary orthography), converted
             from eBible.org's USFM. CC BY-SA 4.0, The Free Bible Foundation. Psalm titles,
             the same Proverbs openings and Habakkuk's closing note are kept apart from the
             verse text.
- icons/*.png drawn here, so no image tooling is needed

Each language's page, manifest and service worker come from release.py, not from here.

Usage: python3 build.py [path/to/bible-scroll]   (default: ../bible-scroll)
"""

import io
import json
import re
import struct
import sys
import urllib.request
import zipfile
import zlib
from difflib import SequenceMatcher
from pathlib import Path

PWA = Path(__file__).resolve().parent
IOS = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else PWA.parent / "bible-scroll"
CATALOG = IOS / "BibleCore/Sources/BibleCore/BookCatalog.swift"
BSB = IOS / "BibleScroll/BibleScroll/Resources/bsb.json"
# The BSB's structured edition marks psalm titles (\d) and closing notes (\mr) that bsb.txt
# runs into the verse text. Downloaded once; only used to find where to cut.
USFM_URL = "https://bereanbible.com/bsb_usfm.zip"
USFM_ZIP = PWA / ".cache" / "bsb_usfm.zip"
PSALMS, PROVERBS, HABAKKUK = 19, 20, 35
PSALM_TITLES = 116
# Section openings that run into the proverb after them. No source marks them (they're plain
# paragraph text), so they're listed. 1:1, 25:1 and 31:1 are whole verses and stay verses.
PROVERB_INTROS = {
    (10, 1): "The proverbs of Solomon:",
    (24, 23): "These also are sayings of the wise:",
    (30, 1): "These are the words of Agur son of Jakeh—the burden that this man declared to Ithiel:",
}
ML_PROVERB_INTROS = {
    (10, 1): "ശലോമോന്റെ സദൃശവാക്യങ്ങൾ",
    (24, 23): "ഇവയും ജ്ഞാനികളുടെ വാക്യങ്ങൾ.",
    (30, 1): "യാക്കേയുടെ മകനായ ആഗൂരിന്റെ വചനങ്ങൾ; ഒരു അരുളപ്പാടു; ആ പുരുഷന്റെ വാക്യമാവിതു:",
}
ML_USFM = "https://ebible.org/Scriptures/mal2015_usfm.zip"
ML_PSALM_TITLES = 117
# This edition has no \mr marker; the note is the last poetry line of Habakkuk 3:19.
ML_HABAKKUK_NOTE = "സംഗീതപ്രമാണിക്കു തന്ത്രിനാദത്തോടെ."

ROW = re.compile(
    r'row\((\d+), "(\w+)", "(\w+)", "([^"]+)",(?: bsb: "([^"]+)",)? slug: "(\w+)", chapters: (\d+)\)'
)


def build_books() -> None:
    books = []
    for m in ROW.finditer(CATALOG.read_text()):
        order, usfm, osis, name, bsb, slug, chapters = m.groups()
        books.append({
            "order": int(order), "usfm": usfm, "osis": osis, "name": name,
            "bsbName": bsb or name, "slug": slug, "chapters": int(chapters),
        })
    assert [b["order"] for b in books] == list(range(1, 67)), "catalog parse failed"
    (PWA / "books.js").write_text(
        "// Generated by pwa/build.py from BookCatalog.swift. Do not edit.\n"
        f"export const BOOKS = {json.dumps(books, separators=(',', ':'))};\n"
    )


def usfm(code: str) -> str:
    if not USFM_ZIP.exists():
        USFM_ZIP.parent.mkdir(exist_ok=True)
        urllib.request.urlretrieve(USFM_URL, USFM_ZIP)
    with zipfile.ZipFile(USFM_ZIP) as z:
        return z.read(f"bsb_usfm/{code}.usfm").decode("utf-8-sig")


def plain(marked: str) -> str:
    """USFM text without footnotes, cross-references or markers."""
    s = re.sub(r"\\[fx] .*?\\[fx]\*", "", marked)
    s = re.sub(r"\\(?:ref|\+?w) ([^|\\]*)\|[^\\]*\\(?:ref|\+?w)\*", r"\1", s)
    s = re.sub(r"\\\+?[a-z0-9]+\*?", "", s)
    return " ".join(s.split())


def cut(verse: str, marked: str, from_end: bool = False) -> tuple[str, str]:
    """Splits `marked`'s words off the start (or end) of `verse`, keeping bsb.txt's wording.

    Returns (the cut words, the rest). The two editions differ by a letter here and there,
    so the cut is by word count and only has to read nearly the same.
    """
    words, n = verse.split(" "), len(marked.split())
    part, rest = (words[-n:], words[:-n]) if from_end else (words[:n], words[n:])
    part, rest = " ".join(part), " ".join(rest)
    same = SequenceMatcher(None, part.lower(), marked.lower()).ratio()
    assert rest and same > 0.9, f"can't find {marked!r} in {verse!r}"
    return part, rest


def write_bible() -> None:
    data = json.loads(BSB.read_text())
    books = data["books"]
    total = sum(len(c) for b in books for c in b)

    titles, chapter = {}, 0
    for line in usfm("PSA").splitlines():
        if line.startswith("\\c "):
            chapter = int(line.split()[1])
        elif line.startswith("\\d \\v 1 "):
            verses = books[PSALMS - 1][chapter - 1]
            titles[f"{PSALMS}:{chapter}"], verses[0] = cut(verses[0], plain(line[8:]))
    assert len(titles) == PSALM_TITLES, f"found {len(titles)} psalm titles"
    for (chapter, verse), intro in PROVERB_INTROS.items():
        verses = books[PROVERBS - 1][chapter - 1]
        titles[f"{PROVERBS}:{chapter}:{verse}"], verses[verse - 1] = cut(verses[verse - 1], intro)

    note = next(plain(l[4:]) for l in usfm("HAB").splitlines() if l.startswith("\\mr "))
    verses, notes = books[HABAKKUK - 1][2], {}
    notes[f"{HABAKKUK}:3:19"], verses[18] = cut(verses[18], note, from_end=True)

    assert sum(len(c) for b in books for c in b) == total
    data["titles"], data["notes"] = titles, notes
    (PWA / "bsb.json").write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")))


# Malayalam: notes (\f, \x) and figures are dropped whole; other character markers keep their text.
ML_NOTE = re.compile(r"\\(f|x|fig) .*?\\\1\*", re.S)
ML_CHAR = re.compile(r"\\\+?[a-z]+\d*(\*| ?)")
# Lines that are not verse text: titles, headings, acrostic letters.
ML_SKIP = re.compile(r"\\(id|h|toc\d|mt\d|ms\d|s\d|r|qa)\b")


def ml_plain(marked: str) -> str:
    return re.sub(r"\s+", " ", ML_CHAR.sub("", marked)).strip()


def write_malayalam() -> None:
    usfm = {}
    # eBible.org refuses urllib's default User-Agent.
    request = urllib.request.Request(ML_USFM, headers={"User-Agent": "curl/8"})
    with zipfile.ZipFile(io.BytesIO(urllib.request.urlopen(request).read())) as z:
        for name in z.namelist():
            if name.endswith(".usfm"):
                text = z.read(name).decode("utf-8-sig")
                usfm[re.match(r"\\id (\w+)", text).group(1)] = text

    order = [b["usfm"] for b in json.loads((PWA / "books.js").read_text().split("= ", 1)[1].rstrip(";\n"))]
    books, titles = [], {}
    for code in order:
        chapters, verse = [], None
        for line in ML_NOTE.sub("", usfm[code]).splitlines():
            line = line.strip()
            if not line or ML_SKIP.match(line):
                continue
            if m := re.match(r"\\d (.*)", line):
                assert code == "PSA" and verse is None, f"unexpected title in {code} {len(chapters)}"
                titles[f"{PSALMS}:{len(chapters)}"] = ml_plain(m.group(1))
                continue
            if m := re.match(r"\\c (\d+)", line):
                chapters.append([])
                assert len(chapters) == int(m.group(1)), f"{code} chapter order"
                verse = None
                continue
            if m := re.match(r"\\v (\d+)\s*(.*)", line):
                verse = int(m.group(1))
                line = m.group(2)
                verses = chapters[-1]
                verses.extend([""] * (verse - len(verses)))
            if verse is None:
                continue
            text = ml_plain(line)
            if text:
                chapters[-1][verse - 1] = f"{chapters[-1][verse - 1]} {text}".strip()
        books.append(chapters)
    assert len(titles) == ML_PSALM_TITLES, f"found {len(titles)} psalm titles"
    for (chapter, verse), intro in ML_PROVERB_INTROS.items():
        verses = books[PROVERBS - 1][chapter - 1]
        assert verses[verse - 1].startswith(f"{intro} "), f"Proverbs {chapter}:{verse} intro not found"
        verses[verse - 1] = verses[verse - 1][len(intro):].lstrip()
        titles[f"{PROVERBS}:{chapter}:{verse}"] = intro

    verses = books[HABAKKUK - 1][2]
    assert verses[18].endswith(f" {ML_HABAKKUK_NOTE}"), "Habakkuk 3:19 note not found"
    verses[18] = verses[18][: -len(ML_HABAKKUK_NOTE)].rstrip()
    notes = {f"{HABAKKUK}:3:19": ML_HABAKKUK_NOTE}

    data = {"translation": "Sathyavedapusthakam 1910", "books": books, "titles": titles, "notes": notes}
    (PWA / "ml").mkdir(exist_ok=True)
    (PWA / "ml" / "mal1910.json").write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")))


def png(size: int) -> bytes:
    """A hanging scroll on white: black rollers top and bottom, a light grey page, a black cross.

    Opaque and full-bleed: iOS rounds the corners itself. Everything stays inside the
    central circle Android keeps when it crops a maskable icon.
    """
    white, page, ink = (255, 255, 255), (236, 236, 240), (28, 28, 30)
    scale = 0.92  # shrinks the drawing about the centre to clear the maskable safe zone
    # Rounded rectangles on a 100-unit tile, drawn in order: (x0, y0, x1, y1, radius, colour).
    shapes = [
        (30, 24, 70, 76, 0, page),
        (22, 17, 78, 26, 4.5, ink),
        (22, 74, 78, 83, 4.5, ink),
        (46.5, 33, 53.5, 67, 1, ink),
        (37, 41, 63, 48, 1, ink),
    ]

    def inside(u: float, v: float, x0, y0, x1, y1, r) -> bool:
        if not (x0 <= u <= x1 and y0 <= v <= y1):
            return False
        dx = max(x0 + r - u, 0, u - (x1 - r))
        dy = max(y0 + r - v, 0, v - (y1 - r))
        return dx * dx + dy * dy <= r * r

    def colour(u: float, v: float):
        c = white
        for *box, fill in shapes:
            if inside(u, v, *box):
                c = fill
        return c

    samples = [(i + 0.5) / 4 for i in range(4)]  # 4x4 supersampling for smooth edges
    to_unit = lambda p: 50 + (p / size * 100 - 50) / scale
    rows = []
    for y in range(size):
        row = bytearray([0])
        for x in range(size):
            hits = [colour(to_unit(x + sx), to_unit(y + sy)) for sx in samples for sy in samples]
            row += bytes(round(sum(h[i] for h in hits) / 16) for i in range(3))
        rows.append(bytes(row))
    raw = zlib.compress(b"".join(rows), 9)

    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data))

    header = struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", raw) + chunk(b"IEND", b"")


def write_icons() -> None:
    # Renamed when the design changes: iOS and the service worker cache icons by URL.
    for size in (180, 192, 512):
        (PWA / "icons" / f"scroll-{size}.png").write_bytes(png(size))


def main() -> None:
    build_books()
    write_bible()
    write_malayalam()
    (PWA / "icons").mkdir(exist_ok=True)
    write_icons()
    print("books.js, bsb.json, ml/mal1910.json, icons written to", PWA)


if __name__ == "__main__":
    main()
